"""Freeze FSRS scheduling cases the Swift port must reproduce (ANA-PLAN §18.1:
"Algoritma birim testleri referans implementasyonla karşılaştırılmalıdır").

    python -m evals.fsrs.export_cases

Same reasoning as `evals/ocr_eval/export_marker_cases.py`: the algorithm runs
in two languages, so the *numbers* are pinned here rather than trusted to
match by construction.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from evals.fsrs.algorithm import MemoryState, load_weights, schedule

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "evals" / "shared" / "fsrs-cases.json"

#: (name, prior_state_or_None, rating, elapsed_days)
CASES: list[tuple[str, tuple[float, float] | None, int, float]] = [
    # --- first review: no prior state, one per rating ---
    ("first_again", None, 1, 0.0),
    ("first_hard", None, 2, 0.0),
    ("first_good", None, 3, 0.0),
    ("first_easy", None, 4, 0.0),
    # --- a young card (low stability/difficulty), reviewed after a few days ---
    ("young_again_3d", (1.5, 4.0), 1, 3.0),
    ("young_hard_3d", (1.5, 4.0), 2, 3.0),
    ("young_good_3d", (1.5, 4.0), 3, 3.0),
    ("young_easy_3d", (1.5, 4.0), 4, 3.0),
    # --- a mature card (high stability), reviewed after a long gap ---
    ("mature_again_60d", (90.0, 3.0), 1, 60.0),
    ("mature_hard_60d", (90.0, 3.0), 2, 60.0),
    ("mature_good_60d", (90.0, 3.0), 3, 60.0),
    ("mature_easy_60d", (90.0, 3.0), 4, 60.0),
    # --- a difficult card (high difficulty), reviewed on schedule ---
    ("hard_card_again_10d", (10.0, 9.0), 1, 10.0),
    ("hard_card_good_10d", (10.0, 9.0), 3, 10.0),
    # --- same-day repeats (elapsed_days < 1) ---
    ("same_day_again", (5.0, 5.0), 1, 0.2),
    ("same_day_hard", (5.0, 5.0), 2, 0.2),
    ("same_day_good", (5.0, 5.0), 3, 0.2),
    ("same_day_easy", (5.0, 5.0), 4, 0.2),
    # --- the exact same-day/long-term boundary ---
    ("boundary_just_under_one_day", (5.0, 5.0), 3, 0.999),
    ("boundary_exactly_one_day", (5.0, 5.0), 3, 1.0),
    # --- reviewed later than scheduled (overdue) ---
    ("overdue_good", (5.0, 5.0), 3, 20.0),
    # --- the lapse clamp's regime: an already-lapsed card left for months ---
    # Pinned because this is the only regime where `_next_stability_failure`'s
    # `min(long_term, S / e^(w17*w18))` term changes the answer. Without it this
    # case leaves "Unuttum" with *more* stability (0.0558) than it went in with
    # (0.05) — a longer interval for a card the user just failed.
    ("lapsed_card_left_for_months", (0.05, 3.0), 1, 100.0),
]


def build_payload() -> dict:
    payload = load_weights()
    w = payload["weights"]
    retention = payload["desiredRetention"]

    cases = []
    for name, prior, rating, elapsed_days in CASES:
        state = MemoryState(stability=prior[0], difficulty=prior[1]) if prior else None
        result_state, interval = schedule(state, rating, elapsed_days, w, retention)
        cases.append(
            {
                "name": name,
                "input": {
                    "priorStability": prior[0] if prior else None,
                    "priorDifficulty": prior[1] if prior else None,
                    "rating": rating,
                    "elapsedDays": elapsed_days,
                },
                "expected": {
                    "stability": result_state.stability,
                    "difficulty": result_state.difficulty,
                    "intervalDays": interval,
                },
            }
        )
    return {
        "_comment": (
            "GENERATED by `python -m evals.fsrs.export_cases`. Expected values "
            "come from the Python FSRS reference (evals/fsrs/algorithm.py). "
            "Both implementations are tested against this file (ANA-PLAN §18.1)."
        ),
        "weightsVersion": payload["version"],
        "cases": cases,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    payload = json.dumps(build_payload(), ensure_ascii=False, indent=2) + "\n"

    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != payload:
            print(
                f"{args.output} güncel değil.\n"
                "Düzeltmek için: python -m evals.fsrs.export_cases",
                file=sys.stderr,
            )
            return 1
        print(f"{args.output} güncel.")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(payload, encoding="utf-8")
    print(f"Yazıldı: {args.output}  ({len(CASES)} vaka)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
